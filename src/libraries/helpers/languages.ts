export type Lang = keyof typeof ALL_LANGUAGES;
export type LanguageInfo = (typeof ALL_LANGUAGES)[Lang];

let activeLanguages: Record<Lang, LanguageInfo> = ALL_LANGUAGES;
let activeLangCodes: Lang[] = Object.keys(ALL_LANGUAGES) as Lang[];

export function setupLanguages(langs: Lang[]) {
  if (!langs || langs.length === 0) {
    throw new Error("At least one language must be provided");
  }

  const filtered: Partial<Record<Lang, LanguageInfo>> = {};
  const codes: Lang[] = [];

  langs.forEach((lang) => {
    if (!ALL_LANGUAGES[lang]) {
      throw new Error(`Language "${lang}" not found. Available: ${Object.keys(ALL_LANGUAGES).join(', ')}`);
    }
    filtered[lang] = ALL_LANGUAGES[lang];
    codes.push(lang);
  });

  activeLanguages = filtered as Record<Lang, LanguageInfo>;
  activeLangCodes = codes;

  return {
    languages: activeLanguages,
    codes: activeLangCodes,
  };
}

export function getLanguages() {
  return activeLanguages;
}

export function getLanguageCodes(): Lang[] {
  return activeLangCodes;
}

export function getLanguage<T extends Lang>(lang: T): LanguageInfo {
  if (!activeLanguages[lang]) {
    throw new Error(`Language "${lang}" is not active. Active: ${activeLangCodes.join(', ')}`);
  }
  return activeLanguages[lang];
}

export function hasLanguage(lang: string): lang is Lang {
  return lang in activeLanguages;
}

export function getAllLanguages() {
  return Object.entries(activeLanguages).map(([code, info]) => ({
    code,
    ...info,
  }));
}